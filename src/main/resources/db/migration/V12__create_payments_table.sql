CREATE TABLE payments
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT         NOT NULL UNIQUE,
    total_amount   DECIMAL(10, 2) NOT NULL DEFAULT 0.00,
    payment_method VARCHAR(50),
    status         VARCHAR(50)    NOT NULL,
    payment_date   TIMESTAMP,
    created_at     TIMESTAMP               DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_payment_appointment FOREIGN KEY (appointment_id) REFERENCES appointments (id) ON DELETE CASCADE
);

CREATE TABLE payment_items
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id     BIGINT         NOT NULL,
    description    VARCHAR(255)   NOT NULL,
    quantity       INT            NOT NULL DEFAULT 1,
    unit_price     DECIMAL(10, 2) NOT NULL,
    subtotal       DECIMAL(10, 2) NOT NULL,
    reference_type VARCHAR(50)    NOT NULL,
    reference_id   BIGINT,
    CONSTRAINT fk_payment_item_payment FOREIGN KEY (payment_id) REFERENCES payments (id) ON DELETE CASCADE
);